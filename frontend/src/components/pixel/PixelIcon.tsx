export type PixelIconName = keyof typeof PIXEL_ICONS;

export function rowsToPath(rows: string[]): string {
  let d = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === "#") {
        let x2 = x;
        while (x2 < row.length && row[x2] === "#") x2++;
        d += `M${x} ${y}h${x2 - x}v1h-${x2 - x}z`;
        x = x2;
      } else {
        x++;
      }
    }
  });
  return d;
}

export interface PixelIconProps {
  name: PixelIconName;
  size?: number;
  className?: string;
  style?: CSSProperties;
  title?: string;
}

export default function PixelIcon({
  name,
  size = 16,
  className,
  style,
  title,
}: PixelIconProps) {
  const rows = PIXEL_ICONS[name];
  if (!rows) return null;
  return (
    <svg
      viewBox="0 0 16 16"
      width={size}
      height={size}
      className={className}
      style={style}
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
    >
      {title ? <title>{title}</title> : null}
      <path d={rowsToPath(rows)} />
    </svg>
  );
}
